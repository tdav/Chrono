"""Код дизайн-системы Chrono из DESIGN.json (тема Apple, chrono.mobile.apple.v1).

Только стандартная библиотека Python. Запуск из корня репозитория:  python tools/gen_design.py
DESIGN.json — источник правды: значения правятся в нём, затем генератор перезаписывает файлы ниже (руками их не правят).
  src/Chrono/Design/ChronoColors.g.cs        — цвета четырёх внешних видов (#AARRGGBB) и псевдонимы старых ключей
  src/Chrono/Design/TextStyles.g.cs          — стили текста Apple: кегль, интерлиньяж, вес, трекинг, Dynamic Type
  src/Chrono/Resources/Styles/Colors.xaml    — цвета светлого вида: значения до запуска ThemeService и для превью XAML
  src/Chrono/Resources/Styles/Metrics.xaml   — отступы, радиусы и размеры (x:Double)
  src/Chrono/Resources/Styles/Typography.xaml — стили Label «Text*» для 24 стилей текста
Проверка: tests/Chrono.Tests/DesignTokensTests.cs сверяет ChronoColors.g.cs и TextStyles.g.cs с DESIGN.json.
"""
import json
import os
import re
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else "."
DESIGN = json.load(open(os.path.join(ROOT, "DESIGN.json"), encoding="utf-8"))
APPEARANCES = ["light", "dark", "lightHighContrast", "darkHighContrast"]
HEADER_CS = (
    "// <auto-generated>\n"
    f"//   Сгенерировано tools/gen_design.py из DESIGN.json ({DESIGN['id']} {DESIGN['version']}). Не править руками:\n"
    "//   значения правятся в DESIGN.json, затем генератор запускается снова.\n"
    "// </auto-generated>\n"
)
HEADER_XAML = (
    f"<!-- Сгенерировано tools/gen_design.py из DESIGN.json ({DESIGN['id']} {DESIGN['version']}). Не править руками. -->\n"
)
# MAUI на Android переводит CharacterSpacing в em с коэффициентом 0.0624 (Microsoft.Maui.Platform.UnitExtensions.ToEm).
MAUI_EM = 0.0624
# Старые кисти темы «Шлифованный металл · Кость»: ключ → токен (заливка) — до переноса экранов.
LEGACY_BRUSHES = {"CanvasBrush": "systemGroupedBackground", "MetalBrush": "tint", "GoldEdgeBrush": "tint"}
# Затухание барабана: цвет панели шторки к прозрачному.
FADE_COLOR = "secondarySystemGroupedBackground"


def pascal(name):
    return name[:1].upper() + name[1:]


def parse(value):
    value = value.strip()
    if value.startswith("#"):
        h = value[1:]
        if len(h) == 6:
            return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 1.0
        if len(h) == 8:  # CSS: #RRGGBBAA
            return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), int(h[6:8], 16) / 255
    m = re.fullmatch(r"rgba\((\d+),(\d+),(\d+),([0-9.]+)\)", value.replace(" ", ""))
    if m:
        return int(m[1]), int(m[2]), int(m[3]), float(m[4])
    raise ValueError(f"Цвет не разобран: {value}")


def resolve(name, appearance, depth=0):
    if depth > 8:
        raise ValueError(f"Цикл ссылок: {name}")
    value = DESIGN["color"][name]
    if isinstance(value, dict):
        value = value[appearance]
    m = re.fullmatch(r"\{(\w+)\}(?:@([0-9.]+))?", value)
    if m:
        r, g, b, a = resolve(m[1], appearance, depth + 1)
        return r, g, b, a * float(m[2] or 1)
    return parse(value)


def argb(rgba):
    r, g, b, a = rgba
    return "#%02X%02X%02X%02X" % (int(a * 255 + 0.5), r, g, b)


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("записан", path)


def colors_cs():
    rows = []
    for name in DESIGN["color"]:
        values = ", ".join(f'"{argb(resolve(name, a))}"' for a in APPEARANCES)
        rows.append(f'        new("{pascal(name)}", {values}),')
    legacy = [(k, pascal(v)) for k, v in DESIGN["legacy"].items() if k != "note" and k != pascal(v)]
    legacy_rows = [f'        ("{old}", "{new}"),' for old, new in legacy]
    return (
        HEADER_CS
        + "namespace Chrono.Design;\n\n"
        + "public static class ChronoColors\n{\n"
        + "    /// <summary>Все цвета DESIGN.json: ключ ресурса и #AARRGGBB для Light, Dark, LightHighContrast, DarkHighContrast.</summary>\n"
        + "    public static readonly IReadOnlyList<ColorToken> All =\n    [\n"
        + "\n".join(rows)
        + "\n    ];\n\n"
        + "    /// <summary>Старые ключи темы «Шлифованный металл · Кость» → ключи новых цветов (DESIGN.json › legacy). Удаляются после переноса экранов.</summary>\n"
        + "    public static readonly IReadOnlyList<(string OldKey, string NewKey)> Legacy =\n    [\n"
        + "\n".join(legacy_rows)
        + "\n    ];\n}\n"
    )


WEIGHTS = {300: "Light", 400: "Regular", 500: "Medium", 600: "Semibold", 700: "Bold"}


def styles():
    return list(DESIGN["type"].items())


def text_styles_cs():
    enum_rows = ["    None,"] + [f"    {pascal(n)}," for n, _ in styles()]
    natural = DESIGN["font"]["android"]["naturalLineHeight"]

    def metric(s):
        max_size = "null" if "maxSize" not in s else f'{s["maxSize"]}'
        return (
            f'new({s["size"]}, {s["lineHeight"]}, TextWeight.{WEIGHTS[s["weight"]]}, {s["tracking"]}, '
            f'DynamicType.{pascal(s["dynamicType"])}, {max_size}, {"true" if s.get("tabular") else "false"})'
        )

    body = dict(styles())["body"]
    metric_rows = [f"        {metric(body)}, // None — как Body"] + [f"        {metric(s)}, // {pascal(n)}" for n, s in styles()]
    return (
        HEADER_CS
        + "namespace Chrono.Design;\n\n"
        + "/// <summary>Стили текста Apple (DESIGN.md §2.4). None — стиль не задан.</summary>\n"
        + "public enum TextStyle\n{\n" + "\n".join(enum_rows) + "\n}\n\n"
        + "public static class TextStyles\n{\n"
        + "    /// <summary>Естественная высота строки Inter (hhea: ascender − descender + lineGap), доля кегля.</summary>\n"
        + f"    public const double AndroidNaturalLineHeight = {natural};\n\n"
        + "    private static readonly TextMetrics[] Metrics =\n    [\n" + "\n".join(metric_rows) + "\n    ];\n\n"
        + "    public static TextMetrics Get(TextStyle style) => Metrics[(int)style];\n}\n"
    )


def colors_xaml():
    lines = [
        '<?xml version="1.0" encoding="UTF-8" ?>',
        HEADER_XAML.rstrip("\n"),
        "<!-- Значения светлого вида. ThemeService при старте и при смене темы или контраста записывает эти ключи в ресурсы",
        "     приложения значениями текущего вида, поэтому в XAML цвета берутся через DynamicResource. -->",
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/dotnet/2021/maui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2009/xaml">',
        "",
    ]
    for name in DESIGN["color"]:
        lines.append(f'    <Color x:Key="{pascal(name)}">{argb(resolve(name, "light"))}</Color>')
    lines += ["", "    <!-- Старые ключи темы «Шлифованный металл · Кость» (DESIGN.json › legacy). Удаляются после переноса экранов. -->"]
    for old, new in DESIGN["legacy"].items():
        if old == "note" or old == pascal(new):
            continue
        lines.append(f'    <Color x:Key="{old}">{argb(resolve(new, "light"))}</Color>')
    for key, token in LEGACY_BRUSHES.items():
        lines.append(f'    <SolidColorBrush x:Key="{key}" Color="{argb(resolve(token, "light"))}" />')
    r, g, b, _ = resolve(FADE_COLOR, "light")
    solid, clear = argb((r, g, b, 1)), argb((r, g, b, 0))
    lines += [
        '    <LinearGradientBrush x:Key="FadeDownBrush" StartPoint="0,0" EndPoint="0,1">',
        f'        <GradientStop Color="{solid}" Offset="0" />',
        f'        <GradientStop Color="{clear}" Offset="1" />',
        "    </LinearGradientBrush>",
        '    <LinearGradientBrush x:Key="FadeUpBrush" StartPoint="0,0" EndPoint="0,1">',
        f'        <GradientStop Color="{clear}" Offset="0" />',
        f'        <GradientStop Color="{solid}" Offset="1" />',
        "    </LinearGradientBrush>",
        "",
        "</ResourceDictionary>",
        "",
    ]
    return "\n".join(lines)


def metrics_xaml():
    lines = [
        '<?xml version="1.0" encoding="UTF-8" ?>',
        HEADER_XAML.rstrip("\n"),
        "<!-- Отступы, радиусы и размеры, pt (DESIGN.md §2.1, §2.5, §2.6). В XAML: HeightRequest=\"{StaticResource SizeRow}\". -->",
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/dotnet/2021/maui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2009/xaml">',
        "",
    ]
    for group, prefix in (("spacing", ""), ("radius", "Radius"), ("size", "Size")):
        for name, value in DESIGN[group].items():
            lines.append(f'    <x:Double x:Key="{prefix}{pascal(name)}">{value}</x:Double>')
        lines.append("")
    lines += ["</ResourceDictionary>", ""]
    return "\n".join(lines)


def num(v):
    return ("%.4f" % v).rstrip("0").rstrip(".")


def typography_xaml():
    natural = DESIGN["font"]["android"]["naturalLineHeight"]
    aliases = DESIGN["font"]["android"]["aliases"]
    lines = [
        '<?xml version="1.0" encoding="UTF-8" ?>',
        HEADER_XAML.rstrip("\n"),
        "<!-- Стили текста Apple (DESIGN.md §2.4): ключ Text + имя стиля. Только типографика, цвет задают стили ролей в Styles.xaml.",
        "     iOS: FontFamily не задаётся — системный SF; шрифт с весом и Dynamic Type строит Platforms/iOS/Design/Typography.iOS.cs",
        "          по design:Typography.Style, трекинг и интерлиньяж SF система ставит сама.",
        "     Android: Inter нужного веса; CharacterSpacing = трекинг (em) / 0.0624 — так MAUI переводит его в em;",
        f"          LineHeight = интерлиньяж / ({natural} × кегль) — множитель естественной высоты строки Inter, только разрежение. -->",
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/dotnet/2021/maui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2009/xaml"',
        '                    xmlns:design="clr-namespace:Chrono.Design">',
        "",
    ]
    for name, s in styles():
        size, lh, w, tr = s["size"], s["lineHeight"], s["weight"], s["tracking"]
        extra = []
        if s.get("tabular"):
            extra.append("табличные цифры")
        if "maxSize" in s:
            extra.append(f"рост до {s['maxSize']}")
        note = f"{size}/{lh}, {WEIGHTS[w]}, трекинг {tr} em, Dynamic Type — {pascal(s['dynamicType'])}" + (", " + ", ".join(extra) if extra else "")
        lines.append(f"    <!-- {name}: {note} -->")
        lines.append(f'    <Style x:Key="Text{pascal(name)}" TargetType="Label">')
        lines.append(f'        <Setter Property="FontSize" Value="{size}" />')
        lines.append(f'        <Setter Property="FontFamily" Value="{{OnPlatform Android={aliases[str(w)]}}}" />')
        # На iOS вес задаёт шрифт из Typography.iOS.cs; Bold — запасной вариант, если стиль перебит локальным FontSize.
        attributes = "{OnPlatform iOS=Bold, Default=None}" if w >= 600 else "None"
        lines.append(f'        <Setter Property="FontAttributes" Value="{attributes}" />')
        spacing = num(tr / MAUI_EM)
        spacing_value = f"{{OnPlatform Android={spacing}, Default=0}}" if spacing != "0" else "0"
        lines.append(f'        <Setter Property="CharacterSpacing" Value="{spacing_value}" />')
        mult = lh / (natural * size)
        lh_value = f"{{OnPlatform Android={num(mult)}, Default=-1}}" if mult > 1.0005 else "-1"
        lines.append(f'        <Setter Property="LineHeight" Value="{lh_value}" />')
        lines.append(f'        <Setter Property="design:Typography.Style" Value="{pascal(name)}" />')
        lines.append("    </Style>")
        lines.append("")
    lines += ["</ResourceDictionary>", ""]
    return "\n".join(lines)


write("src/Chrono/Design/ChronoColors.g.cs", colors_cs())
write("src/Chrono/Design/TextStyles.g.cs", text_styles_cs())
write("src/Chrono/Resources/Styles/Colors.xaml", colors_xaml())
write("src/Chrono/Resources/Styles/Metrics.xaml", metrics_xaml())
write("src/Chrono/Resources/Styles/Typography.xaml", typography_xaml())
